"""Dataset interface and provenance record.

There is intentionally no real dataset in this repository yet.  What exists is
the shape every future one must fit:

    dry audio  +  wet audio  +  the parameter setting that produced the wet
    audio  +  a :class:`DatasetInfo` saying where it came from and what may be
    done with it.

:class:`DatasetInfo` is not paperwork.  A trained model inherits the licence of
the data it was fitted to, and "it was downloadable" is not a licence.  The
exporter copies these fields into the ``.fbmx`` header so a released model can
always be traced back to its source and its terms.  Adapters that cannot fill
in ``license`` and ``source`` fail loudly instead of defaulting to something
permissive.
"""

from __future__ import annotations

import hashlib
import json
from dataclasses import asdict, dataclass, field
from pathlib import Path
from typing import Any, Iterable, Mapping, Sequence

import torch
from torch.utils.data import Dataset

from fbmx.conditioning import ConditioningSchema, ParamBatch

__all__ = [
    "SOURCE_TYPES",
    "DatasetInfo",
    "PairedSequenceDataset",
    "PairedItem",
    "collate_pairs",
    "file_sha256",
]

#: How the wet signal came into existence.  Recorded per dataset and copied
#: into the exported model, because the honesty of a model claim depends on it.
SOURCE_TYPES = (
    "synthetic",  # procedurally generated by code in this repo
    "circuit_model",  # rendered by a teacher DSP / circuit simulation
    "hardware_capture",  # recorded from physical hardware
    "hybrid",  # a mixture; explain in `notes`
)


def file_sha256(path: str | Path, chunk: int = 1 << 20) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as fh:
        while True:
            block = fh.read(chunk)
            if not block:
                break
            h.update(block)
    return h.hexdigest()


@dataclass
class DatasetInfo:
    """Provenance and licence record for one dataset.

    Required for every adapter, including synthetic ones.  ``redistributable``
    defaults to ``False``: a dataset is assumed un-redistributable until
    somebody has read its terms and said otherwise.
    """

    name: str
    source: str  # URL, hardware rig description, or module path
    source_type: str  # one of SOURCE_TYPES
    license: str  # SPDX id where possible, else free text
    version: str = "0"
    sample_rate: int = 48000
    license_url: str = ""
    attribution: str = ""  # required credit text, verbatim
    citation: str = ""
    checksum: str = ""  # content hash of the dataset as used
    redistributable: bool = False
    notes: str = ""
    extra: dict[str, Any] = field(default_factory=dict)

    def __post_init__(self) -> None:
        if self.source_type not in SOURCE_TYPES:
            raise ValueError(
                f"source_type must be one of {SOURCE_TYPES}, got {self.source_type!r}"
            )
        for required in ("name", "source", "license"):
            if not getattr(self, required):
                raise ValueError(f"DatasetInfo.{required} must not be empty")
        if self.sample_rate <= 0:
            raise ValueError("sample_rate must be positive")

    def to_dict(self) -> dict[str, Any]:
        return asdict(self)

    @staticmethod
    def from_dict(d: Mapping[str, Any]) -> "DatasetInfo":
        known = {f for f in DatasetInfo.__dataclass_fields__}
        return DatasetInfo(**{k: v for k, v in d.items() if k in known})

    def summary(self) -> str:
        redis = "redistributable" if self.redistributable else "NOT redistributable"
        return (
            f"{self.name} v{self.version} [{self.source_type}] "
            f"{self.sample_rate} Hz, licence {self.license} ({redis})"
        )


@dataclass
class PairedItem:
    """One training example: a dry/wet pair at one parameter setting."""

    dry: torch.Tensor  # [1, T]
    wet: torch.Tensor  # [1, T]
    params: ParamBatch  # single row
    key: str = ""
    aux: dict[str, torch.Tensor] = field(default_factory=dict)

    def __post_init__(self) -> None:
        if self.dry.shape != self.wet.shape:
            raise ValueError(
                f"{self.key}: dry {tuple(self.dry.shape)} != wet {tuple(self.wet.shape)}"
            )
        if self.dry.dim() != 2 or self.dry.shape[0] != 1:
            raise ValueError(f"{self.key}: expected mono [1, T], got {tuple(self.dry.shape)}")
        if self.params.batch_size != 1:
            raise ValueError(f"{self.key}: params must be a single row")


class PairedSequenceDataset(Dataset):
    """Base class for every dry/wet dataset.

    Items are *whole sequences*, not pre-cut windows: the trainer is
    responsible for chunking them and for carrying recurrent state across the
    chunks (TBPTT).  Cutting windows here would destroy exactly the long-memory
    structure that these models exist to learn.
    """

    def __init__(self, info: DatasetInfo, schema: ConditioningSchema | None = None) -> None:
        self.info = info
        self.schema = schema or ConditioningSchema()
        self.sample_rate = info.sample_rate

    def __len__(self) -> int:  # pragma: no cover - abstract
        raise NotImplementedError

    def __getitem__(self, index: int) -> PairedItem:  # pragma: no cover - abstract
        raise NotImplementedError

    # -- shared helpers -------------------------------------------------
    def describe(self) -> str:
        return f"{type(self).__name__}: {len(self)} sequences | {self.info.summary()}"

    def provenance(self) -> dict[str, Any]:
        return {"dataset": self.info.to_dict(), "conditioning": self.schema.to_dict()}

    def validate(self, limit: int | None = 8) -> None:
        """Sanity-check a few items: shapes, dtype, finiteness, range."""
        n = len(self) if limit is None else min(limit, len(self))
        for i in range(n):
            item = self[i]
            for name, t in (("dry", item.dry), ("wet", item.wet)):
                if t.dtype != torch.float32:
                    raise TypeError(f"{item.key}: {name} must be float32, got {t.dtype}")
                if not torch.isfinite(t).all():
                    raise ValueError(f"{item.key}: {name} contains NaN or Inf")


def collate_pairs(items: Sequence[PairedItem]) -> dict[str, Any]:
    """DataLoader collate that keeps :class:`ParamBatch` intact.

    Sequences in a batch must be equal length; the datasets in this repo
    guarantee that per split, and a mixed-length corpus should be bucketed by
    the adapter rather than zero-padded (padding a recurrent model's state with
    silence is a silent correctness bug, not a convenience).
    """
    lengths = {int(i.dry.shape[-1]) for i in items}
    if len(lengths) != 1:
        raise ValueError(f"collate_pairs got mixed sequence lengths: {sorted(lengths)}")
    batch: dict[str, Any] = {
        "dry": torch.stack([i.dry for i in items], dim=0),  # [B, 1, T]
        "wet": torch.stack([i.wet for i in items], dim=0),
        "params": ParamBatch.collate([i.params for i in items]),
        "keys": [i.key for i in items],
    }
    aux_keys: Iterable[str] = set().union(*[set(i.aux) for i in items]) if items else ()
    if aux_keys:
        batch["aux"] = {
            k: torch.stack([i.aux[k] for i in items], dim=0)
            for k in aux_keys
            if all(k in i.aux for i in items)
        }
    return batch


def dump_provenance(datasets: Iterable[PairedSequenceDataset], path: str | Path) -> None:
    """Write the provenance of every dataset used in a run next to the run."""
    payload = [d.provenance() for d in datasets]
    Path(path).write_text(json.dumps(payload, indent=2), encoding="utf-8")
